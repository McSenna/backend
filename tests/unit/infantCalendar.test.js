'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
assert.ok(fs.existsSync(path.join(__dirname, '../../services/immunization/calendar.js')), 'infant calendar module is implemented');
const { todayManila, addDays, addMonths, ageOn, targetDate } = require('../../services/immunization/calendar');
assert.equal(todayManila(new Date('2026-10-22T16:00:00Z')), '2026-10-23');
assert.equal(todayManila(new Date('2026-10-22T15:59:59Z')), '2026-10-22');
assert.equal(addDays('2024-01-01', 42), '2024-02-12');
assert.equal(addDays('2024-01-01', 70), '2024-03-11');
assert.equal(addDays('2024-01-01', 98), '2024-04-08');
assert.equal(addMonths('2024-02-29', 12), '2025-02-28');
assert.equal(addMonths('2023-05-31', 9), '2024-02-29');
assert.equal(addMonths('2026-01-31', 1), '2026-02-28');
assert.deepEqual(ageOn('2026-01-31', '2026-03-02'), {months:1,days:2,weeks:4});
assert.deepEqual(ageOn('2024-02-29', '2025-02-28'), {months:12,days:0,weeks:52});
assert.equal(targetDate('2024-01-01', {days:42}), '2024-02-12');
assert.throws(() => addDays('2024-02-30', 1));
assert.throws(() => ageOn('2027-01-01', '2026-01-01'));
const { INITIAL_SCHEDULE } = require('../../services/immunization/scheduleDefinition');
assert.equal(INITIAL_SCHEDULE.vaccines.length, 7);
assert.equal(INITIAL_SCHEDULE.vaccines.flatMap(v => v.doses).length, 15);
assert.equal(INITIAL_SCHEDULE.vaccines.find(v => v.key === 'opv').route, 'Oral (by mouth)');
assert.equal(INITIAL_SCHEDULE.vaccines.find(v => v.key === 'hepb').doses.length, 1);
assert.deepEqual(INITIAL_SCHEDULE.slots.map(s => s.label), ['At birth','6 weeks','10 weeks','14 weeks','9 months','12 months']);
assert.equal(INITIAL_SCHEDULE.activationStatus, 'pending_verification');
const { buildDoseViews } = require('../../services/immunization/checklist');
const baby = { dateOfBirth:'2026-01-01' };
const schedule = {...INITIAL_SCHEDULE,activationStatus:'active',dueWindowDays:7};
const views = (records, today) => buildDoseViews(baby, schedule, records, today);
assert.equal(views([], '2026-02-12').find(d => d.key === 'opv-1').status, 'Due');
assert.equal(views([], '2026-02-19').find(d => d.key === 'opv-1').status, 'Due');
assert.equal(views([], '2026-02-20').find(d => d.key === 'opv-1').status, 'Overdue');
assert.equal(views([], '2026-02-11').find(d => d.key === 'opv-1').status, 'Upcoming');
assert.equal(views([{doseKey:'opv-1',state:'administered',historical:true}], '2026-02-20').find(d => d.key === 'opv-1').status, 'Administered');
assert.equal(views([{doseKey:'opv-1',state:'void'}], '2026-02-20').find(d => d.key === 'opv-1').status, 'Requires review');
assert.equal(views([{doseKey:'opv-1',state:'deferred',followUpOn:'2026-02-25'}], '2026-02-20').find(d => d.key === 'opv-1').scheduledOn, '2026-02-25');
console.log('Infant date, schedule and status assertions passed');
