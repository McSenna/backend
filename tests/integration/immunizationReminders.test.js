"use strict";
const assert = require("node:assert/strict");
const mongoose = require("mongoose");
const { MongoMemoryReplSet } = require("mongodb-memory-server");
const User = require("../../models/User");
const Notification = require("../../models/Notification");
const { runImmunizationReminders } = require("../../services/immunization/reminderWorker");
const Baby = require("../../models/Baby");
const Dose = require("../../models/ImmunizationDose");
const Schedule = require("../../models/VaccineSchedule");
const Reminder = require("../../models/ImmunizationReminder");
const { presentProtectedNotifications, mapToNotificationItem } = require("../../services/notification/notificationPresenter");

(async () => {
  const repl = await MongoMemoryReplSet.create({ replSet: { count: 1 } });
  try {
    await mongoose.connect(repl.getUri());
    await Promise.all([User.init(), Baby.init(), Dose.init(), Schedule.init(), Notification.init(), Reminder.init()]);
    const now = new Date("2026-10-23T00:00:00Z");
    const recipient = new mongoose.Types.ObjectId();
    const babyId = new mongoose.Types.ObjectId();
    await User.collection.insertOne({ _id: recipient, fullname: "Test Mother", email: "reminders@example.test", role: "resident", status: "active", verified: true, verificationMethod: "master_list", masterResidentId: "MOTHER-1", immunizationRemindersEnabled: true });
    await Baby.collection.insertOne({ _id: babyId, name: "Test Baby", dateOfBirth: "2026-10-23", motherMasterResidentId: "MOTHER-1", scheduleVersion: "test-v1", revision: 0, createdBy:recipient, requestKey:"test-birth-a" });
    await Schedule.collection.insertOne({ version: "test-v1", title: "Test schedule", source: "Verified clinical source", effectiveOn: "2026-01-01", activationStatus: "active", dueWindowDays: 7, reminderDays: [7,1,0], slots: [{ key: "birth", label: "Birth", days: 0 }], vaccines: [{ key: "vaccine-a", name: "Vaccine A", disease: "A", route: "ID", doses: [{ key: "a1", label: "First", slot: "birth" }, { key: "a2", label: "Second", slot: "birth" }] }] });
    await Promise.all([runImmunizationReminders({ now }), runImmunizationReminders({ now })]);
    assert.equal(await Notification.countDocuments({ type: "immunization_reminder" }), 1, "parallel workers group same-day doses once");
    let notice = await Notification.findOne({ type: "immunization_reminder" }).lean();
    assert.ok(!JSON.stringify(mapToNotificationItem(notice)).includes("Test Baby"), "realtime preview contains no health detail");
    let protectedRows = await presentProtectedNotifications([notice], recipient);
    assert.equal(protectedRows[0].immunizationDetail.babyName, "Test Baby");
    assert.equal(protectedRows[0].immunizationDetail.vaccines.length, 2);
    await runImmunizationReminders({ now });
    assert.equal(await Notification.countDocuments(), 1, "repeat evaluation does not duplicate");
    await User.updateOne({ _id: recipient }, { $unset: { masterResidentId: "" } });
    protectedRows = await presentProtectedNotifications([notice], recipient);
    assert.ok(!protectedRows[0].immunizationBabyId && !protectedRows[0].immunizationDetail, "unlink immediately suppresses protected detail before the next worker tick");
    await runImmunizationReminders({ now });
    assert.equal(await Reminder.countDocuments({ status: "cancelled" }), 1);
    await User.updateOne({ _id: recipient }, { $set: { masterResidentId: "MOTHER-1" } });
    await runImmunizationReminders({ now });
    assert.equal(await Notification.countDocuments(), 1, "unlink and relink cannot redeliver an existing visit/stage");

    await Dose.collection.insertOne({babyId,doseKey:"a1",state:"administered",administeredOn:"2026-10-23",revision:1});
    await require("../../services/immunization/reminderWorker").cancelPendingForBaby(babyId);
    await runImmunizationReminders({now});
    notice = await Notification.findOne().lean();
    protectedRows = await presentProtectedNotifications([notice],recipient);
    assert.deepEqual(protectedRows[0].immunizationDetail.vaccines.map(v=>v.key),["a2"],"remaining due vaccine retains a live notice after another dose is saved");
    assert.equal(await Notification.countDocuments(),1,"refreshes original notice without another delivery");
    await Dose.deleteMany({});
    await Notification.deleteMany({}); await Reminder.deleteMany({});
    const originalUpdate = Notification.updateOne;
    Notification.updateOne = function failStorage() { throw new Error("injected transient storage failure"); };
    try { await runImmunizationReminders({ now }); } finally { Notification.updateOne = originalUpdate; }
    const retry = await Reminder.findOne().lean();
    assert.equal(retry.attempts, 1);
    assert.equal(retry.status, "pending");
    assert.ok(retry.nextAttemptAt > now);
    await runImmunizationReminders({ now });
    assert.equal(await Notification.countDocuments(), 0, "backoff prevents immediate retry");
    await runImmunizationReminders({ now: new Date(now.getTime() + 61000) });
    assert.equal(await Notification.countDocuments(), 1, "failed delivery retries after backoff");

    await Dose.collection.insertOne({ babyId, doseKey: "a1", state: "administered", administeredOn: "2026-10-23", revision: 1 });
    await Dose.collection.insertOne({ babyId, doseKey: "a2", state: "void", revision: 1 });
    await runImmunizationReminders({ now });
    notice = await Notification.findOne().lean();
    protectedRows = await presentProtectedNotifications([notice], recipient);
    assert.ok(!protectedRows[0].immunizationDetail, "completion and void cancel outdated reminder detail");
    await Reminder.deleteMany({}); await Notification.deleteMany({}); await Dose.deleteMany({});
    await Schedule.updateOne({ version: "test-v1" }, { $set: { activationStatus: "pending_verification" } });
    await runImmunizationReminders({ now });
    assert.equal(await Notification.countDocuments(), 0, "unverified schedule never activates reminders");
    await Schedule.updateOne({ version: "test-v1" }, { $set: { activationStatus: "active" } });
    await User.updateOne({ _id: recipient }, { $set: { immunizationRemindersEnabled: false } });
    await runImmunizationReminders({ now });
    assert.equal(await Notification.countDocuments(), 0, "opt out prevents delivery");
    await User.updateOne({_id:recipient},{$set:{immunizationRemindersEnabled:true}});
    await runImmunizationReminders({now});
    const twinId = new mongoose.Types.ObjectId();
    await Baby.collection.insertOne({_id:twinId,name:"Test Twin",dateOfBirth:"2026-10-23",motherMasterResidentId:"MOTHER-1",scheduleVersion:"test-v1",revision:0,createdBy:recipient,requestKey:"test-birth-b"});
    await runImmunizationReminders({now});
    assert.equal(await Notification.countDocuments(),2,"twins receive independent baby-specific grouped reminders");
    await Dose.collection.insertOne({babyId,doseKey:"a1",state:"deferred",followUpOn:"2026-10-30",revision:1});
    await runImmunizationReminders({now});
    assert.equal(await Notification.countDocuments({immunizationBabyId:babyId}),2,"rescheduled visit gets a seven-day stage");
    const futureNotice = await Notification.findOne({immunizationBabyId:babyId,'immunizationDetail.scheduledOn':"2026-10-30"}).lean();
    assert.deepEqual(futureNotice.immunizationDetail.vaccines.map(v=>v.key),["a1"]);
    assert.ok((await Reminder.findOne({dedupeKey:futureNotice.dedupeKey})).deliveredAt);
    console.log("Immunization reminder worker passed");
  } finally { await mongoose.disconnect(); await repl.stop(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
