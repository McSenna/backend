'use strict';
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const h = require('./helpers/medicalRecordHarness');
const Record = require('../../models/MedicalRecord');
const SystemLog = require('../../models/SystemLog');
const Appointment = require('../../models/Appointment');
const User = require('../../models/User');
const Baby = require('../../models/Baby');
const Dose = require('../../models/ImmunizationDose');
const {initializeImmunization} = require('../../services/immunization/initialize');
const call = (user,body,headers) => h.request('/medical-record-masterlist/delete',{method:'POST',headers:headers || (user ? h.as(user) : {}),body});
const input = record => ({recordId:String(record._id),reason:'Duplicate entry confirmed against source card',expectedUpdatedAt:new Date(record.updatedAt).toISOString()});
(async () => {
 let failed = false;
 try {
  await h.setupWithFixtures();
  const bhw = await h.createStaff('bhw'), other = await h.createStaff('bhw'), admin = await h.createStaff('admin'), doctor = await h.createStaff('doctor'), midwife = await h.createStaff('midwife'), resident = await h.createStaff('resident');
  await User.updateOne({_id:resident._id},{$set:{masterResidentId:'TEST-F'}});
  const encoded = (await h.encode(bhw,h.bpRecord({requestKey:'deleted-retry-key'}))).body.detail;
  const record = await Record.findById(encoded._id).lean();
  assert.equal((await call(null,input(record))).status,401);
  assert.equal((await call(resident,input(record),h.asResident(resident))).status,403);
  assert.equal((await call(other,input(record))).status,403);
  assert.equal((await call(doctor,input(record))).status,403);
  assert.equal((await call(bhw,{...input(record),reason:' '})).status,400);
  assert.equal((await call(bhw,{...input(record),reason:'x'.repeat(501)})).status,400);
  assert.equal((await call(bhw,{...input(record),expectedUpdatedAt:'2020-01-01T00:00:00.000Z'})).status,409);
  const tokenHeaders = h.as(bhw);
  await User.updateOne({_id:bhw._id},{$set:{role:'doctor'}});
  assert.equal((await call(bhw,input(record),tokenHeaders)).status,403,'role is refreshed from database');
  await User.updateOne({_id:bhw._id},{$set:{role:'bhw'}});
  const rows = (await h.search(bhw)).body.records;
  assert.equal(rows[0].createdById,String(bhw._id));
  assert.equal(rows[0].updatedAt,record.updatedAt.toISOString());
  const result = await call(bhw,input(record));
  assert.equal(result.status,200,JSON.stringify(result.body));
  assert.ok(await SystemLog.findOne({action:'MEDICAL_RECORD_DELETED',resourceId:String(record._id)}),'deletion has a system log without clinical content');
  assert.deepEqual(result.body,{success:true,recordId:String(record._id),deleted:true});
  assert.equal((await call(bhw,input(record))).body.deleted,false,'retry does not add an audit revision');
  assert.equal(await Record.findById(record._id),null);
  assert.equal((await h.request(`/medical-records/${record._id}`,{headers:h.asResident(resident)})).status,404);
  assert.equal((await h.request('/medical-record-masterlist/summary',{headers:h.as(admin)})).body.summary.total,0);
  assert.deepEqual((await h.search(admin,{masterResidentId:'TEST-F'})).body.serviceCounts,{});
  assert.equal(await Record.countDocuments({_id:record._id}),0);
  assert.equal((await Record.aggregate([{$match:{_id:record._id}}])).length,0);
  assert.equal((await h.search(bhw)).body.pagination.total,0);
  assert.equal((await h.request(`/medical-record-masterlist/${record._id}`,{headers:h.as(bhw)})).status,404);
  assert.equal((await h.myRecordPage(resident)).body.medicalRecords.length,0);
  const archived = await Record.findById(record._id).withDeleted().lean();
  assert.equal(String(archived.deletedBy),String(bhw._id));
  assert.equal(archived.deletedByRole,'bhw');
  assert.equal(archived.deletionReason,input(record).reason);
  assert.equal(archived.revisions.length,1);
  assert.equal(archived.revisions[0].changes[0].field,'deletedAt');
  assert.equal((await h.encode(bhw,h.bpRecord({requestKey:'deleted-retry-key'}))).status,409,'an encoding retry cannot recreate an archived record');
  assert.equal(archived.serviceDetails.systolic,130,'clinical values are retained');
  const visit = await Appointment.create({resident:resident._id,consultationType:'general_checkup',status:'completed',ageTier:4,prioritySortKey:4});
  const appointmentId = visit._id;
  const visitBefore = JSON.stringify(await Appointment.findById(appointmentId).lean());
  const appointment = await Record.create({resident:resident._id,appointment:appointmentId,provider:doctor._id,providerRole:'doctor',serviceType:'general_checkup',assessment:'Fictional consultation',completedAt:new Date()});
  const otherDoctor = await h.createStaff('doctor');
  assert.equal((await call(otherDoctor,input(appointment))).status,403,'another provider cannot delete appointment record');
  assert.equal((await call(admin,input(appointment))).status,403,'admin is read-only for appointment records');
  assert.ok(await Record.findById(appointment._id),'admin deletion denial keeps the record visible');
  assert.equal((await call(doctor,input(appointment))).status,200,'responsible provider may delete appointment record');
  assert.equal(JSON.stringify(await Appointment.findById(appointmentId).lean()),visitBefore,'appointment status and scheduling remain unchanged');
  assert.equal((await h.request(`/medical-records/${appointmentId}`,{headers:h.as(doctor)})).status,404,'alternate appointment detail is hidden');
  const ownedAppointment = await Record.create({resident:resident._id,appointment:new mongoose.Types.ObjectId(),provider:doctor._id,providerRole:'doctor',serviceType:'general_checkup',assessment:'Fictional consultation',completedAt:new Date()});
  assert.equal((await call(doctor,input(ownedAppointment))).status,200,'provider may delete appointment record');
  await initializeImmunization();
  const baby = (await h.request('/immunization/babies',{method:'POST',headers:h.as(midwife),body:{motherMasterResidentId:'TEST-F',dateOfBirth:'2026-01-01',requestKey:'delete-baby'}})).body.baby;
  const draftBody = {motherMasterResidentId:'TEST-F',babyId:baby._id,doseKey:'bcg-1',expectedRevision:null,remarks:'Pending source card',historical:true};
  assert.equal((await h.request('/immunization/drafts',{method:'POST',headers:h.as(midwife),body:draftBody})).status,200);
  const program = await Record.findOne({immunizationBabyId:baby._id}).lean();
  assert.equal(program.workflowStatus,'draft');
  const doseBefore = JSON.stringify(await Dose.find({babyId:baby._id}).lean());
  assert.equal((await call(admin,input(program))).status,403,'immunization restricted to midwives');
  await User.updateOne({_id:resident._id},{$set:{verificationMethod:'admin_review',status:'active',verified:true}});
  const secondMidwife = await h.createStaff('midwife');
  assert.equal((await call(secondMidwife,input(program))).status,200,'any midwife can remove program summary');
  const {setRealtimeServer} = require('../../realtime/broadcast');
  const events = [];
  setRealtimeServer({sockets:{sockets:new Map()},to:rooms=>({except:()=>({emit:(event,payload)=>events.push({rooms,event,payload})})})});
  try {await require('../../realtime/publishers/medicalRecords').publish([{id:String(program._id),action:'updated',updatedKeys:['deletedAt']}]);}
  finally {setRealtimeServer(null);}
  assert.equal(events.length,2);
  assert.deepEqual(events[0],{rooms:['role:admin','role:midwife'],event:'medicalRecord:deleted',payload:{id:String(program._id)}});
  assert.deepEqual(events[1],{rooms:[`user:${resident._id}`],event:'myMedicalRecord:deleted',payload:{id:String(program._id)}});
  assert.equal(JSON.stringify(await Dose.find({babyId:baby._id}).lean()),doseBefore);
  assert.equal(await Record.findOne({immunizationBabyId:baby._id}),null);
  const checklist = await h.request('/immunization/checklist',{method:'POST',headers:h.as(midwife),body:draftBody});
  assert.equal(checklist.body.medicalRecord,null,'checklist hides archived summary but keeps dose history');
  assert.ok(checklist.body.history.length);
  await initializeImmunization();
  assert.equal(await Record.findOne({immunizationBabyId:baby._id}),null,'startup never resurrects deleted summary');
  const dose = await Dose.findOne({babyId:baby._id}).lean();
  assert.equal((await h.request('/immunization/drafts',{method:'POST',headers:h.as(midwife),body:{...draftBody,expectedRevision:dose.revision,remarks:'New explicit clinical save'}})).status,200);
  const replacement = await Record.findOne({immunizationBabyId:baby._id}).lean();
  assert.notEqual(String(replacement._id),String(program._id));
  assert.equal(String((await Record.findById(program._id).withDeleted().lean()).deletedImmunizationBabyId),baby._id);
  assert.equal((await Baby.findById(baby._id).lean())._id.toString(),baby._id);
  // Completed programs use exactly the same deletion path as drafts.
  await Record.updateOne({_id:replacement._id},{$set:{recordStatus:'completed',workflowStatus:'completed'}});
  const completed = await Record.findById(replacement._id).lean();
  assert.equal((await call(midwife,input(completed))).status,200);
  console.log('Medical record deletion authorization, retention, visibility, retries and immunization lifecycle passed');
 } catch(error) {failed=true;console.error(error);}
 await h.finish(failed);
})();
