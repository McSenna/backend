'use strict';
const assert = require('node:assert/strict');
const h = require('./helpers/medicalRecordHarness');
const call = (path, user, body) => h.request(`/immunization${path}`, {method:'POST',headers:user.role === 'resident' ? h.asResident(user) : h.as(user),body});
(async () => {
  let failed = false;
  try {
    await h.setupWithFixtures();
    const midwife = await h.createStaff('midwife');
    const response = await call('/babies', midwife, {motherMasterResidentId:'TEST-F',dateOfBirth:'2026-01-31',requestKey:'birth-twin-a'});
    assert.equal(response.status,201, 'midwife can record a birth linked to an existing mother');
    const baby = response.body.baby;
    const Baby = require('../../models/Baby');
    const Dose = require('../../models/ImmunizationDose');
    const VaccineSchedule = require('../../models/VaccineSchedule');
    await Promise.all([Baby.init(),Dose.init(),VaccineSchedule.init()]);
    assert.ok(baby.temporaryName);
    const twin = await call('/babies', midwife, {motherMasterResidentId:'TEST-F',dateOfBirth:'2026-01-31',requestKey:'birth-twin-b'});
    assert.equal(twin.status,201); assert.notEqual(twin.body.baby._id,baby._id);
    const replay = await call('/babies', midwife, {motherMasterResidentId:'TEST-F',dateOfBirth:'2026-01-31',requestKey:'birth-twin-a'});
    assert.equal(replay.body.baby._id,baby._id);
    const context = {motherMasterResidentId:'TEST-F',babyId:baby._id};
    let checklist = await call('/checklist',midwife,context);
    assert.equal(checklist.status,200); assert.equal(checklist.body.accountLinked,false);
    assert.equal(checklist.body.doses.filter(d => d.status === 'Administered').length,0);
    assert.equal(checklist.body.doses.find(d => d.key === 'opv-1').targetOn,'2026-03-14');
    const admin = await h.createStaff('admin');
    const mother = await h.createStaff('resident');
    const stranger = await h.createStaff('resident');
    const User = require('../../models/User');
    await User.updateOne({_id:mother._id},{$set:{masterResidentId:'TEST-F',verificationMethod:'admin_review',status:'active',verified:true}});
    const MedicalRecord = require('../../models/MedicalRecord');
    const legacyId = (await MedicalRecord.collection.insertOne({resident:mother._id,serviceType:'immunization',completedAt:new Date('2026-02-01'),serviceDetails:{vaccineName:'Ambiguous paper record'}})).insertedId;
    const legacyBefore = JSON.stringify(await MedicalRecord.findById(legacyId).lean());
    await require('../../services/immunization/initialize').initializeImmunization();
    assert.equal(JSON.stringify(await MedicalRecord.findById(legacyId).lean()),legacyBefore,'initialization preserves ambiguous legacy records');
    assert.equal((await call('/checklist',midwife,context)).body.legacyReviewRequired,true);
    assert.equal(await Dose.countDocuments(),0,'ambiguous legacy text never auto-checks a dose');
    await User.updateOne({_id:stranger._id},{$set:{masterResidentId:'TEST-A',verificationMethod:'admin_review',status:'active',verified:true}});
    for (const role of ['admin','doctor','bhw','resident']) {
      const actor = role === 'resident' ? mother : role === 'admin' ? admin : await h.createStaff(role);
      for (const path of ['/babies','/babies/rename','/administrations','/corrections','/follow-up']) {
        assert.equal((await call(path, actor, {...context,doseKey:'bcg-1'})).status,403,`${role} cannot write ${path}`);
      }
    }
    assert.equal((await h.request('/immunization/administrations',{method:'POST',body:context})).status,401);
    assert.equal((await call('/checklist',stranger,context)).status,403);
    assert.equal((await call('/checklist',mother,context)).status,200);
    assert.equal((await call('/checklist',midwife,{...context,motherMasterResidentId:'TEST-A'})).status,404);
    for (const date of ['2026-01-30','2999-01-01','2026-02-30']) {
      assert.equal((await call('/administrations',midwife,{...context,doseKey:'bcg-1',administeredOn:date})).status,400);
    }
    assert.equal((await call('/administrations',midwife,{...context,doseKey:'unknown',administeredOn:'2026-01-31'})).status,400);
    assert.equal(await Dose.countDocuments(),0,'failed saves do not complete doses');
    const dose = {...context,doseKey:'bcg-1',administeredOn:'2026-01-31',historical:true,administeredBy:'Historical test clinician',recordedBy:String(admin._id)};
    const saves = await Promise.all([call('/administrations',midwife,dose),call('/administrations',midwife,dose)]);
    assert.deepEqual(saves.map(r=>r.status).sort(),[201,409]);
    assert.equal(await Dose.countDocuments({babyId:baby._id,doseKey:'bcg-1'}),1);
    let record = await Dose.findOne({babyId:baby._id,doseKey:'bcg-1'}).lean();
    assert.equal(String(record.recordedBy),String(midwife._id));
    assert.equal(record.administeredBy,'Historical test clinician');
    assert.equal(await Dose.countDocuments({babyId:twin.body.baby._id}),0);
    checklist = await call('/checklist',mother,context);
    assert.equal(checklist.body.doses.find(d=>d.key==='bcg-1').status,'Administered');
    assert.equal(checklist.body.doses.find(d=>d.key==='bcg-1').reviewRequired,true);
    assert.equal((await call('/corrections',midwife,{...context,doseKey:'bcg-1',action:'void',expectedRevision:record.revision})).status,400);
    const corrected = await call('/corrections',midwife,{...context,doseKey:'bcg-1',action:'correct',reason:'Correct paper transcription',expectedRevision:record.revision,administration:{administeredOn:'2026-02-01',historical:true,administeredBy:'Historical test clinician'}});
    assert.equal(corrected.status,200,JSON.stringify(corrected.body));
    assert.equal((await call('/corrections',midwife,{...context,doseKey:'bcg-1',action:'void',reason:'Stale test correction',expectedRevision:record.revision})).status,409);
    record = await Dose.findOne({babyId:baby._id,doseKey:'bcg-1'}).lean();
    assert.equal(record.history.length,2); assert.equal(record.history[1].previous.administeredOn,'2026-01-31');
    assert.equal((await call('/corrections',midwife,{...context,doseKey:'bcg-1',action:'void',reason:'Wrong baby on source card',expectedRevision:record.revision})).status,200);
    record = await Dose.findOne({babyId:baby._id,doseKey:'bcg-1'}).lean();
    assert.equal(record.state,'void'); assert.equal(record.history.length,3);
    assert.equal((await call('/follow-up',midwife,{...context,doseKey:'opv-1',followUpOn:'2999-01-01',reason:'Clinical follow-up',deferred:true})).status,200);
    assert.equal((await call('/babies/rename',midwife,{...context,name:'Test newborn A'})).status,200);
    assert.equal((await Baby.findById(baby._id)).name,'Test newborn A');
    assert.equal(await Dose.countDocuments({babyId:baby._id}),2);
    await User.updateOne({_id:mother._id},{$unset:{masterResidentId:1}});
    assert.equal((await call('/checklist',mother,context)).status,403,'unlink applies immediately');
    await User.updateOne({_id:mother._id},{$set:{masterResidentId:'TEST-F'}});
    const Appointment = require('../../models/Appointment');
    const {todayManila} = require('../../services/immunization/calendar');
    const visitDay = todayManila();
    const appointment = await Appointment.create({resident:mother._id,consultationType:'immunization',status:'confirmed',slotStart:new Date(visitDay+'T00:00:00Z'),ageTier:0,prioritySortKey:0});
    const visitContext = {...context,appointmentId:String(appointment._id)};
    assert.equal((await call('/visits/complete',midwife,{...visitContext,babyId:twin.body.baby._id})).status,409,'empty ledger does not complete a clinical visit');
    assert.equal((await call('/administrations',midwife,{...context,doseKey:'opv-2',administeredOn:visitDay})).status,201);
    const completedVisit = await call('/visits/complete',midwife,visitContext);
    assert.equal(completedVisit.status,200,JSON.stringify(completedVisit.body));
    const replayVisit = await call('/visits/complete',midwife,visitContext);
    assert.equal(replayVisit.body.medicalRecord._id,completedVisit.body.medicalRecord._id,'visit completion replays without duplicate record');
    assert.deepEqual(completedVisit.body.medicalRecord.serviceDetails,{ledgerSummary:true},'legacy summary contains no baby identity or clinical ledger IDs');
    const {addDays}=require('../../services/immunization/calendar');
    const {nextThursday}=require('../../services/immunization/appointmentPlan');
    const priorThursday=nextThursday(addDays(visitDay,-7));
    const activeVisit=await Appointment.create({resident:mother._id,consultationType:'immunization',immunizationBabyId:baby._id,immunizationVisitKey:`${baby._id}:${mother._id}:${priorThursday}`,immunizationTargetOn:priorThursday,immunizationDoseKeys:['penta-1'],status:'processing',slotStart:new Date(priorThursday+'T08:00:00+08:00'),ageTier:0,prioritySortKey:0});
    const correctedMother=await h.createStaff('resident');
    await User.updateOne({_id:mother._id},{$unset:{masterResidentId:1}});
    await User.updateOne({_id:correctedMother._id},{$set:{masterResidentId:'TEST-F',verificationMethod:'admin_review',status:'active',verified:true}});
    assert.equal((await call('/administrations',midwife,{...context,doseKey:'penta-1',administeredOn:priorThursday,historical:true,administeredBy:'Fictional clinician'})).status,201);
    await Appointment.create({resident:correctedMother._id,consultationType:'immunization',immunizationBabyId:baby._id,immunizationVisitKey:`${baby._id}:${correctedMother._id}:${priorThursday}`,immunizationTargetOn:priorThursday,status:'cancelled',immunizationCancellationOrigin:'system',ageTier:0,prioritySortKey:0});
    const resolved=await call('/visits/complete',midwife,{...context,appointmentId:String(activeVisit._id)});
    assert.equal(resolved.status,200,'midwife resolves a corrected account link when completing the same identified baby visit');
    assert.equal(String(resolved.body.appointment.resident),String(correctedMother._id));
    assert.equal(resolved.body.appointment.immunizationVisitKey,activeVisit.immunizationVisitKey,'clinical completion retains the immutable reservation key despite historical account cycles');
    assert.equal(String(resolved.body.appointment.immunizationAccountHistory[0].previous),String(mother._id));
    const ownAppointments=await require('../../services/appointment/bookingService').listResidentAppointments(correctedMother._id);
    assert.ok(ownAppointments.some(row=>String(row._id)===String(activeVisit._id)));
    assert.ok(ownAppointments.every(row=>!row.immunizationAccountHistory),'old account linkage audit is staff-only');
    assert.equal((await h.encode(midwife,{...h.bpRecord(),serviceType:' immunization '})).status,400,'normalized legacy vaccine writes require baby checklist');
    const visit = await call('/visits/complete',midwife,{...context,appointmentId:'invalid'});
    assert.equal(visit.status,400,'visit completion validates appointment identity');
    const legacy = await h.encode(admin,{...h.bpRecord(),serviceType:'immunization'});
    assert.equal(legacy.status,403,'admin cannot bypass permission through old encoding API');
    console.log('Infant immunization HTTP, ownership, twins, dates, concurrency and audit assertions passed');
  } catch (error) {failed=true; console.error(error);}
  await h.finish(failed);
})();
