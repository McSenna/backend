"use strict";
const assert = require("node:assert/strict");
const http = require("http");
const mongoose = require("mongoose");
const { io: connect } = require("socket.io-client");
const h = require("./helpers/masterListHarness");
const User = require("../../models/User");
const { createApp } = require("../../app");
const { attachRealtime, closeRealtime } = require("../../realtime/socketServer");
const { broadcast } = require("../../realtime/broadcast");
const { userRoom } = require("../../realtime/rooms");
const password = "SyntheticPassword123!";
const account = (role, suffix) => User.create({ fullname: `Synthetic ${suffix}`, email: `${suffix}@maslogcare.test`, password, role, status: role === "resident" ? "approved" : "active", verified: true, gender: "female", dateOfBirth: new Date("1990-01-01"), address: "Test address" });
const authorization = (token) => ({ Authorization: `Bearer ${token}` });
const login = (user, extra = {}) => h.request("/login", { method: "POST", body: { email: user.email, password, clientPlatform: "web", ...extra } });
const once = (socket, event) => new Promise((resolve, reject) => { const timer = setTimeout(() => reject(new Error(`Timed out: ${event}`)), 5000); socket.once(event, (value) => { clearTimeout(timer); resolve(value); }); });
async function run() {
  await h.setup();
  const admin = await account("admin", "admin");
  process.env.RESIDENT_WEB_ACCESS_ADMIN_ID = String(admin._id);
  const resident = await account("resident", "allowed");
  const other = await account("resident", "denied");
  await User.collection.updateOne({ _id: other._id }, { $unset: { residentWebAccessOverride: "", residentWebAccessEnabled: "", webAccessRevision: "" } });
  const headers = h.asAdmin(admin);
  const get = () => h.request("/admin/resident-web-access", { headers });
  const global = (enabled, revision) => h.request("/admin/resident-web-access", { method: "PATCH", headers, body: { enabled, revision } });
  const individual = (user, override, revision = 0) => h.request(`/admin/users/${user._id}/web-access`, { method: "PATCH", headers, body: { override, revision } });
  const initial = await get();
  assert.equal(initial.status, 200, "admin policy endpoint exists");
  assert.equal(initial.body.policy.initialized, false);
  assert.equal((await login(resident)).status, 503, "missing policy fails closed");
  const { initializeResidentWebAccess } = require("../../services/residentWebAccess");
  await initializeResidentWebAccess();
  let state = (await get()).body.policy;
  assert.equal(state.enabled, false, "migration preserves mobile-only policy");
  await initializeResidentWebAccess();
  assert.deepEqual((await get()).body.policy, state, "migration is idempotent");
  assert.equal((await login(resident)).status, 403);
  assert.equal((await global(true, state.revision)).status, 200);
  assert.equal((await login(resident)).status, 200, "no override follows the global setting");
  assert.equal((await individual(resident, "allow")).status, 200);
  assert.equal((await individual(resident, "block")).status, 409, "stale individual save");
  const rows = (await h.request("/users?page=1&per_page=20", { headers })).body.users;
  assert.equal(rows.find((user) => user.id === String(resident._id)).portalAccess.web, true);
  assert.equal(rows.find((user) => user.id === String(other._id)).portalAccess.override, null);
  const web = await login(resident);
  assert.equal(web.status, 200, JSON.stringify(web.body));
  const webHeaders = authorization(web.body.token);
  assert.equal((await h.request("/session/access", { headers: webHeaders })).status, 200);
  const selfEdit = await h.request("/profile", { method: "PATCH", headers: webHeaders, body: { residentWebAccessOverride: "block", residentWebAccessEnabled: false, webAccessRevision: 999 } });
  assert.equal(selfEdit.status, 400, "access flags cannot be mass assigned through profile");
  assert.equal((await User.findById(resident._id).lean()).webAccessRevision, 1);
  await initializeResidentWebAccess();
  assert.equal((await get()).body.policy.enabled, true, "startup preserves persisted global choice");
  assert.equal((await User.findById(resident._id).lean()).residentWebAccessOverride, "allow", "startup preserves individual choice");
  assert.equal((await h.request("/profile", { headers: webHeaders })).status, 200);
  const otherWeb = await login(other);
  assert.equal(otherWeb.status, 200, "no override follows the global setting");
  const otherHeaders = authorization(otherWeb.body.token);
  assert.equal((await global(false, 0)).status, 409, "stale global save");
  assert.equal((await global("false", 1)).status, 400);
  assert.equal((await individual(admin, "allow")).status, 404);
  assert.equal((await h.request("/admin/resident-web-access")).status, 401);
  assert.equal((await h.request("/admin/resident-web-access", { method: "PATCH", headers: webHeaders, body: { enabled: false, revision: 1 } })).status, 403);
  const bhw = await account("bhw", "bhw");
  assert.equal((await h.request("/admin/resident-web-access", { headers: h.asAdmin(bhw) })).status, 403);
  const plainMobile = require("jsonwebtoken").sign({ userId: String(resident._id), role: "resident", platform: "mobile" }, process.env.JWT_SECRET);
  assert.equal((await h.request("/profile", { headers: authorization(plainMobile) })).status, 200, "a mobile session needs no device setup");
  const nativeOldApp = await login(resident, { clientPlatform: "mobile", deviceCredential: null });
  assert.equal(nativeOldApp.status, 200, "an older app's empty credential field is ignored");
  const blockedOnWeb = await account("resident", "blockedweb");
  await individual(blockedOnWeb, "block");
  assert.equal((await login(blockedOnWeb)).status, 403);
  const browserClaimingMobile = await h.request("/login", { method: "POST", headers: { Origin: "http://localhost:8081" }, body: { email: blockedOnWeb.email, password, clientPlatform: "mobile" } });
  assert.equal(browserClaimingMobile.status, 403, "a browser claiming mobile is still treated as web");
  const devicePath = `/admin/users/${resident._id}/devices`;
  assert.equal((await h.request(devicePath, { method: "POST", headers, body: {} })).status, 404, "device provisioning was removed");
  const mobile = await login(resident, { clientPlatform: "mobile" });
  assert.equal(mobile.status, 200, JSON.stringify(mobile.body));
  const mobileHeaders = authorization(mobile.body.token);
  const audit = await require("../../models/SystemLog").find({ action: { $in: ["RESIDENT_WEB_POLICY_CHANGED", "RESIDENT_WEB_ACCESS_CHANGED"] } }).lean();
  assert.ok(audit.some((entry) => entry.action === "RESIDENT_WEB_POLICY_CHANGED"));
  const restartProbe = `const mongoose=require('mongoose');(async()=>{await mongoose.connect(process.env.PROBE_URI);await require('./services/residentWebAccess').initializeResidentWebAccess();const policy=await require('./models/ResidentWebPolicy').findById('resident-web').lean();const user=await require('./models/User').findById(process.env.PROBE_USER).lean();require('node:assert/strict').equal(policy.enabled,true);require('node:assert/strict').equal(user.residentWebAccessOverride,'allow');await mongoose.disconnect()})().catch(()=>process.exit(1));`;
  require("node:child_process").execFileSync(process.execPath, ["-e", restartProbe], { env: { ...process.env, PROBE_URI: mongoose.connection.getClient().s.url, PROBE_USER: String(resident._id) }, stdio: "pipe" });
  assert.equal((await h.request("/profile", { headers: mobileHeaders })).status, 200);
  const socketServer = http.createServer(createApp()); attachRealtime(socketServer);
  await new Promise((resolve) => socketServer.listen(0, "127.0.0.1", resolve));
  const url = `http://127.0.0.1:${socketServer.address().port}`;
  const open = async (token) => { const socket = connect(url, { transports: ["websocket"], auth: { token }, reconnection: false, autoConnect: false }); const ready = once(socket, "connect"); socket.connect(); await ready; return socket; };
  const socket = await open(web.body.token); const followsGlobal = await open(otherWeb.body.token); const native = await open(mobile.body.token);
  try {
    state = (await get()).body.policy;
    const disconnected = once(followsGlobal, "disconnect"); await global(false, state.revision); await disconnected;
    assert.equal(socket.connected, true, "an allow override keeps its web socket when global turns off");
    assert.equal(native.connected, true);
    assert.equal((await h.request("/support/options", { headers: otherHeaders })).status, 200, "blocked resident retains the existing support flow");
    assert.equal((await h.request("/support/tickets/my", { headers: otherHeaders })).status, 200);
    assert.equal((await h.request("/logout", { method: "POST", headers: otherHeaders, body: {} })).status, 200);
    assert.equal((await h.request("/profile", { headers: otherHeaders })).status, 403);
    assert.equal((await h.request("/profile", { headers: webHeaders })).status, 200, "allow override wins while global is off");
    assert.equal((await h.request("/profile", { headers: mobileHeaders })).status, 200);
    assert.equal((await h.request("/users", { headers })).status, 200);
    assert.equal((await User.findById(resident._id).lean()).residentWebAccessOverride, "allow");
    state = (await get()).body.policy; await global(true, state.revision);
    assert.equal((await h.request("/profile", { headers: otherHeaders })).status, 200, "same web token restores");
    assert.equal((await individual(resident, "block", 1)).status, 200);
    assert.equal((await h.request("/profile", { headers: webHeaders })).status, 403);
    await individual(resident, "allow", 2);
    await User.updateOne({ _id: resident._id }, { $set: { status: "suspended" } });
    assert.equal((await h.request("/profile", { headers: webHeaders })).status, 401);
    assert.equal((await login(resident)).status, 403);
    await User.updateOne({ _id: resident._id }, { $set: { status: "approved" } });
    const Policy = require("../../models/ResidentWebPolicy");
    const guarded = await open(otherWeb.body.token); let leaked = false;
    guarded.on("profile:updated", () => { leaked = true; });
    await Policy.updateOne({ _id: "resident-web" }, { $set: { enabled: false } });
    const drop = once(guarded, "disconnect");
    broadcast("profile", "updated", { protected: "synthetic" }, [userRoom(String(other._id))]);
    await drop; assert.equal(leaked, false); guarded.close();
    await Policy.updateOne({ _id: "resident-web" }, { $set: { enabled: true } });
    assert.equal((await h.request(`${devicePath}/${new mongoose.Types.ObjectId()}`, { method: "DELETE", headers })).status, 404, "device revocation was removed");
    assert.equal((await h.request("/profile", { headers: mobileHeaders })).status, 200);
    assert.equal((await h.request("/profile", { headers: webHeaders })).status, 200);
    for (const status of ["pending", "rejected", "deactivated", "inactive"]) {
      await User.updateOne({ _id: resident._id }, { $set: { status, verified: false } });
      assert.equal((await h.request("/profile", { headers: webHeaders })).status, 401, status);
    }
    await User.deleteOne({ _id: resident._id });
    assert.equal((await h.request("/profile", { headers: webHeaders })).status, 401);
    await Policy.deleteMany({});
    assert.equal((await h.request("/profile", { headers: authorization(h.tokenFor(other)) })).status, 503);
    assert.equal((await h.request("/users", { headers })).status, 200);
    const recoveries = await Promise.all([global(false, 0), global(true, 0)]);
    assert.deepEqual(recoveries.map((result) => result.status).sort(), [200, 409], "concurrent recovery has one winner");
    state = (await get()).body.policy;
    // Sending the current value writes nothing, so only the real change can land.
    const concurrent = await Promise.all([global(state.enabled, state.revision), global(!state.enabled, state.revision)]);
    assert.equal(concurrent.filter((result) => result.body.changed === true).length, 1, "concurrent saves cannot silently overwrite");
    assert.equal((await get()).body.policy.enabled, !state.enabled);
  } finally { socket.close(); followsGlobal.close(); native.close(); closeRealtime(); await new Promise((resolve) => socketServer.close(resolve)); }
  console.log("Resident web policy, password-only mobile sign-in, REST and realtime assertions passed");
}
run().then(() => h.teardown()).catch(async (error) => { console.error(error); closeRealtime(); await h.teardown(); process.exitCode = 1; });
